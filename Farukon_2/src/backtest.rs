    /// A position still open when the data ends keeps its last-bar market PnL exactly once: the
    /// final settle pass must not re-book the bar the loop already closed.
    #[test]
    fn settle_without_pending_fills_leaves_capital_unchanged() {
        let (strategy_settings, instruments) = fractional_test_setup();
        let (event_sender, event_receiver) = std::sync::mpsc::channel();
        let mut data_handler = StubDataHandler::new(SYMBOL);
        let mut portfolio = Portfolio::new(
            &"Optimize".to_string(),
            &10_000.0,
            event_sender.clone(),
            &strategy_settings,
            &instruments,
        )
        .unwrap();
        let execution =
            crate::execution::SimulatedExecutionHandler::new(event_sender.clone()).unwrap();

        portfolio.update_timeindex(&data_handler);
        event_sender.send(signal("LONG", 0.5)).unwrap();
        drain_events(
            &event_receiver,
            &mut portfolio,
            &execution,
            &mut data_handler,
            &strategy_settings,
            &instruments,
            "Optimize",
        )
        .unwrap();
        // The last bar is closed with the position still open: its market move is booked here.
        portfolio.update_timeindex(&data_handler);
        let capital_open_position = portfolio.get_latest_holdings().unwrap().capital;

        let settled = settle_final_events(
            &event_receiver,
            &mut portfolio,
            &execution,
            &mut data_handler,
            &strategy_settings,
            &instruments,
            "Optimize",
        )
        .unwrap();

        assert_eq!(settled, 0, "nothing was queued");
        assert_eq!(
            portfolio.get_latest_holdings().unwrap().capital,
            capital_open_position,
            "an empty settle pass must not re-book the last bar's market PnL"
        );
    }
